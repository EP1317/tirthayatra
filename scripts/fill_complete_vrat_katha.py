def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    updated = []
    for item in data["items"]:
        slug = item["slug"]
        if slug not in COMPLETE:
            continue
        item["verses"] = COMPLETE[slug]
        item["completeText"] = True
        item["meaning"] = MEANINGS.get(slug, item.get("meaning", ""))
        if "Complete" not in item.get("summary", ""):
            item["summary"] = "Complete traditional vrat katha. " + item.get("summary", "")
        updated.append(slug)

    data["types"]["vrat-katha"]["lede"] = (
        "Complete vow-stories for Pradosh, Ekadashi, Janmashtami, Navaratri, Ganesh Chaturthi, "
        "Ram Navami, Hanuman Jayanti, and Ayyappa Mandala — with video to listen along."
    )
    disc = data["section"].get("disclaimer", "")
    data["section"]["disclaimer"] = (
        "Aarti, Chalisa, and Vrat Katha pages carry complete traditional texts as widely recited in popular devotion. "
        "Regional wording can differ. Audio/video players use popular public YouTube recordings for convenience; "
        "TirthaYatra does not host the media files. This is for devotion and cultural learning — not a substitute "
        "for guidance from your family priest or temple."
    )
    if "YouTube" not in disc and "YouTube" not in data["section"]["disclaimer"]:
        pass  # already included above

    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {len(updated)} complete vrat kathas:")
    for s in updated:
        print(f"  {s}: {len(COMPLETE[s])} sections")


