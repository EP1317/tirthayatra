    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {len(updated)} complete aarti/chalisa texts:")
    for s in updated:
        n = len(COMPLETE[s])
        print(f"  {s}: {n} stanzas")


